import { readFile, writeFile } from 'node:fs/promises';

// Bundle the same tested policy and provider adapter for Kapso's standalone handler format.
const modules = ['errors.mjs', 'cal-client.mjs', 'handler.mjs'];
const source = (await Promise.all(modules.map(async name => (await readFile(new URL(name, import.meta.url), 'utf8'))
  .replace(/^import .*;\n/gm, '').replace(/^export /gm, '')))).join('\n');
const wrapper = `
async function handler(request, env) {
  const body = await request.json();
  const exchange = body.data_exchange;
  if (!exchange || typeof exchange.flow_token !== 'string') return Response.json({ error: 'Expected data_exchange and flow_token' }, { status: 400 });
  const flowId = body.flow?.id;
  if (typeof flowId !== 'string' || !flowId) return Response.json({ error: 'Expected flow.id' }, { status: 400 });
  const prefix = 'flowso-booking:' + flowId + ':';
  const sessions = {
    async get(token) { return env.KV.get(prefix + token, { type: 'json' }); },
    async set(token, value) {
      // Retry storage only: never replay the provider call after it may have succeeded.
      for (let attempt = 0; ; attempt++) {
        try { await env.KV.put(prefix + token, JSON.stringify(value), { expirationTtl: 3600 }); return; }
        catch (error) {
          if (attempt >= 2 || !/429|too many requests/i.test(String(error?.message))) throw error;
          await new Promise(resolve => setTimeout(resolve, 1100));
        }
      }
    }
  };
  const cal = createCalClient({ baseUrl: env.CAL_API_BASE_URL || 'https://api.cal.com/v2', apiKey: env.CAL_API_KEY,
    eventTypeIds: (env.CAL_EVENT_TYPE_IDS ?? env.CAL_EVENT_TYPE_ID ?? '').split(',').map(value => Number(value.trim())), timeZone: env.CAL_TIME_ZONE || 'UTC',
    allowBookings: env.CAL_ALLOW_BOOKINGS === '1', bookingEnabledUntil: env.CAL_BOOKING_ENABLED_UNTIL });
  return Response.json(await createBookingHandler(cal, sessions)(exchange));
}
`;
await writeFile(new URL('kapso-data-endpoint.js', import.meta.url), '// Generated by node build-kapso-endpoint.mjs; edit the source modules.\n' + source + wrapper);
console.log('Built kapso-data-endpoint.js');
